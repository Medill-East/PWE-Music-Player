export const dictionaries = { zh, en };

export function translate(language, key, values = {}) {
  const template = dictionaries[language]?.[key] ?? zh[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ""));
}
